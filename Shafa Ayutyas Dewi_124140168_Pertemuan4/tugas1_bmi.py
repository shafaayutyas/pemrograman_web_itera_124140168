berat_badan = input("Masukkan berat badan Anda (kg): ")
tinggi_badan = input("Masukkan tinggi badan Anda (cm): ")

print(type(berat_badan))
print(type(tinggi_badan))

# Konversi str ke int
berat_badan = int(berat_badan)
tinggi_badan = int(tinggi_badan)

# Hitung nilai BMI menggunakan rumus:
BMI = berat_badan / (tinggi_badan/100)**2

# Gunakan struktur percabangan if-elif-else untuk menentukan dan menampilkan kategori BMI
if BMI < 18.5:
    kategori="Berat badan kurang"
elif 18.5 <= BMI < 25:
    kategori="Berat badan normal"
elif 25 <= BMI < 30:
    kategori="Berat badan berlebih"
elif BMI >= 30:
    kategori="Obesitas"

print(f"Berdasarkan perhitungan, indeks massa tubuh anda adalah {BMI:,.2f} dan anda tergolong {kategori}")