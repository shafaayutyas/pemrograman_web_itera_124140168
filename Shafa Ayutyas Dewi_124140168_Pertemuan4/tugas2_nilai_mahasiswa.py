#Hitung nilai akhir setiap mahasiswa berdasarkan bobot persentase
for mhs in mahasiswa:
    mhs["nilai_akhir"] = 0.30 * mhs["nilai_uts"] + 0.40 * mhs["nilai_uas"] + 0.30 * mhs["nilai_tugas"]

# Tentukan grade nilai setiap mahasiswa berdasarkan kriteria
for mhs in mahasiswa:
  if mhs["nilai_akhir"] >= 80:
      mhs["grade"] = "A"
  elif 70 <= mhs["nilai_akhir"] < 80:
      mhs["grade"] = "B"
  elif 60 <= mhs["nilai_akhir"] < 70:
      mhs["grade"] = "C"
  elif 50 <= mhs["nilai_akhir"] < 60:
      mhs["grade"] = "D"
  else:
      mhs["grade"] = "E"

# Tampilkan seluruh data mahasiswa secara lengkap (Nama, NIM, Nilai Akhir, dan Grade) dalam format tabel yang rapi di terminal
for index, mhs in enumerate(mahasiswa, 1):
    print(f"\t{index}. Mahasiswa {index}")
    print(f"\tNama: {mhs['nama']}")
    print(f"\tNIM: {mhs['nim']}")
    print(f"\tNilai Akhir: {mhs['nilai_akhir']}")
    print(f"\tGrade: {mhs ['grade']}")
    print("\n")

# Cari dan tampilkan informasi mahasiswa yang memperoleh nilai akhir tertinggi dan nilai akhir terendah
